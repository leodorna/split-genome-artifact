#!/usr/bin/env python3
"""The island-local baselines under the torch.compile modes (Table S4 of the supplement).

max-autotune-no-cudagraphs is the paper's baseline (evox_autotune.sh, 10 seeds);
default is the earlier baseline (evox/, 10 seeds); reduce-overhead (CUDA Graphs) is the
probe of evox_modes.sh (3 seeds).

Per operator and cell: the baseline's time per generation in each mode relative to the
default mode (the paper's baselines), and our speedup, with the heuristic's and with the
tuned configuration, against the fastest mode of that cell. Times are medians over
seeds of the per-seed median.

Usage: analyze_compile_modes.py [--dir results/rerun_v3]
Needs DIR/analysis/launch_heuristic_cells.csv (launch_heuristic.py) for our times.
"""
import argparse
import csv
import os
import statistics as st
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OPS = ["de-gen", "ga-gen", "ux-bf"]
MODES = ["max-autotune-no-cudagraphs", "reduce-overhead"]


def load(path, label):
    per = defaultdict(list)
    if not os.path.exists(path):
        return {}
    for r in csv.DictReader(open(path)):
        # island-local runs only: N counts all rows, so a panmictic run is one island of N > 1024
        if (r["mode"] == label and r["per_gen_median_us"] not in ("oom", "")
                and not (int(r["islands"]) == 1 and int(r["N"]) > 1024)):
            per[(int(r["N"]), int(r["D"]), int(r["islands"]))].append(float(r["per_gen_median_us"]))
    return {k: st.median(v) for k, v in per.items()}


def fmt(xs):
    return f"{st.median(xs):.2f} ({min(xs):.2f}-{max(xs):.2f})" if xs else "-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.path.join(HERE, "..", "results", "rerun_v3"))
    a = ap.parse_args()
    ours = defaultdict(dict)
    for r in csv.DictReader(open(os.path.join(a.dir, "analysis", "launch_heuristic_cells.csv"))):
        k = (r["op"], int(r["I"]) * int(r["N"]), int(r["D"]), int(r["I"]))
        ours[k][r["family"]] = (float(r["heur_us"]), float(r["best_us"]))

    lines = ["== baseline time in each mode / default mode, median (range) over the nine cells"]
    rows = []
    for op in OPS:
        base = load(os.path.join(a.dir, "evox", f"evox_gen_{op}.csv"), "compiled")
        src = {"max-autotune-no-cudagraphs": os.path.join(a.dir, "evox_autotune"),
               "reduce-overhead": os.path.join(a.dir, "evox_modes", "reduce-overhead")}
        modes = {m: load(os.path.join(src[m], f"evox_gen_{op}.csv"), f"compiled-{m}") for m in MODES}
        for m in MODES:
            lines.append(f"  {op:7} {m:28} {fmt([modes[m][k] / base[k] for k in modes[m] if k in base])}")
        for k in sorted(base):
            times = {"default": base[k], **{m: modes[m][k] for m in MODES if k in modes[m]}}
            best_mode = min(times, key=times.get)
            for fam, (h, t) in ours.get((op,) + k, {}).items():
                rows.append(dict(op=op, family=fam, rows=k[0], D=k[1], I=k[2], best_mode=best_mode,
                                 baseline_default_us=times["default"], baseline_best_us=times[best_mode],
                                 speedup_heur_default=times["default"] / h, speedup_heur_best=times[best_mode] / h,
                                 speedup_tuned_best=times[best_mode] / t))
    lines.append("\n== our speedup: heuristic vs default mode | heuristic vs fastest mode | tuned vs fastest mode")
    for op in OPS:
        for fam in ("scalar", "vec4"):
            rs = [r for r in rows if r["op"] == op and r["family"] == fam]
            if rs:
                lines.append(f"  {op:7} {fam:6} {fmt([r['speedup_heur_default'] for r in rs])} | "
                             f"{fmt([r['speedup_heur_best'] for r in rs])} | {fmt([r['speedup_tuned_best'] for r in rs])}")
    best = defaultdict(int)
    for r in rows:
        if r["family"] == "scalar":
            best[(r["op"], r["best_mode"])] += 1
    lines.append("\n== fastest mode per cell: " + ", ".join(f"{op} {m}: {n}" for (op, m), n in sorted(best.items())))
    lines.append(f"   cases where the heuristic is slower than the fastest mode: "
                 f"{sum(r['speedup_heur_best'] < 1 for r in rows)} of {len(rows)}")
    # Table S4: per operator, baseline time relative to the default mode, and our speedups
    def mr(xs):
        return f"{st.median(xs):.2f} ({min(xs):.2f}--{max(xs):.2f})"
    tex = ["% generated by scripts/analyze_compile_modes.py"]
    for op in OPS:
        base = load(os.path.join(a.dir, "evox", f"evox_gen_{op}.csv"), "compiled")
        rel = {}
        for m, src in (("max-autotune-no-cudagraphs", os.path.join(a.dir, "evox_autotune")),
                       ("reduce-overhead", os.path.join(a.dir, "evox_modes", "reduce-overhead"))):
            t = load(os.path.join(src, f"evox_gen_{op}.csv"), f"compiled-{m}")
            rel[m] = [t[k] / base[k] for k in t if k in base]
        for i, fam in enumerate(("scalar", "vec4")):
            rs = [r for r in rows if r["op"] == op and r["family"] == fam]
            first = (f"\\texttt{{{ {"de-gen": "de", "ga-gen": "sbx-pm"}.get(op, op) }}} & {mr(rel['max-autotune-no-cudagraphs'])} & {mr(rel['reduce-overhead'])}"
                     if i == 0 else " & & ")
            famtex = "scalar" if fam == "scalar" else "\\texttt{vec4}"
            tex.append(f"{first} & {famtex} & {mr([r['speedup_heur_default'] for r in rs])} & "
                       f"{mr([r['speedup_heur_best'] for r in rs])} \\\\")
    open(os.path.join(a.dir, "analysis", "table_compile_modes_supp.tex"), "w").write("\n".join(tex) + "\n")
    txt = "\n".join(lines)
    print(txt)
    out = os.path.join(a.dir, "evox_modes")
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "compile_modes_summary.txt"), "w").write(txt + "\n")
    with open(os.path.join(out, "compile_modes_cells.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


if __name__ == "__main__":
    main()

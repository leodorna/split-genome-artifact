#!/usr/bin/env python3
"""Table S3 of the supplement: our kernels against the baselines, best fitness.

For every function, operator and launch configuration, at generations 10, 100 and 1000:
the relative difference of the median best fitness (ours / baseline - 1) with its 95%
percentile-bootstrap interval, and the p-value of the two-sided Mann-Whitney U test
(10 seeds per side). Read from the quality_summary.csv files of analyze_quality.py.
Also prints, per function, the smallest Holm-adjusted p over all its tests (best and
mean fitness, every generation and configuration) and the widest interval at each
generation, for the caption.

Usage: quality_table.py [--ref results/rerun_v3] [--transfer results/transfer] [--out FILE]
"""
import argparse
import csv
import os

from analyze_quality import holm

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = {"s1": "scalar, $s=1$", "s8": "scalar, $s=8$", "s8defer": "scalar, $s=8$, deferred",
       "v4s1": "\\texttt{vec4}, $s=1$", "v4s8": "\\texttt{vec4}, $s=8$",
       "s4w": "scalar, $s=4$, $t_x=128$", "s2w": "scalar, $s=2$, $t_x=64$",
       "s1w": "scalar, $s=1$, $t_x=512$", "heur": "scalar, heuristic"}
ORDER = ["s1", "s8", "s8defer", "v4s1", "v4s8", "s4w", "s2w", "heur"]
# the large-D cell (results/largeD): its unsplit run is s1 with t_x = 512, and the heuristic
# splits with s = 4 (de) or 8 (sbx-pm, ux-bf), t_x = 512
HEUR_S = {"de-gen": 4, "ga-gen": 8, "ux-bf": 8}
GENS = [10, 100, 1000]


def rows(path):
    return list(csv.DictReader(open(path)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default=os.path.join(HERE, "..", "results", "rerun_v3"))
    ap.add_argument("--transfer", default=os.path.join(HERE, "..", "results", "transfer"))
    ap.add_argument("--large", default=os.path.join(HERE, "..", "results", "largeD"))
    ap.add_argument("--out", default=os.path.join(HERE, "..", "results", "transfer", "table_quality_supp.tex"))
    a = ap.parse_args()

    families = [("Sphere / OneMax ($D = 1024$, 4096 bits)", os.path.join(a.ref, "quality"),
                 {"de-gen": "Sphere", "ga-gen": "Sphere", "ux-bf": "OneMax"})]
    for f, name in (("cec-f1", "$f_1$"), ("cec-f2", "$f_2$"), ("cec-f3", "$f_3$"), ("cec-f12", "$f_{12}$")):
        families.append((f"{name} ($D = 1000$, official shift)", os.path.join(a.transfer, f, "quality"),
                         {"de-gen": name, "ga-gen": name}))
    families.append(("Knapsack (4096 items)", os.path.join(a.transfer, "knapsack", "quality"),
                     {"ux-bf": "Knapsack"}))

    if os.path.exists(os.path.join(a.large, "quality", "quality_summary.csv")):
        families.append(("Sphere / OneMax, large $D$ ($I = 1$, $N = 64$, $D = 2^{20}$, $2^{25}$ bits)",
                         os.path.join(a.large, "quality"), {"de-gen": "Sphere", "ga-gen": "Sphere", "ux-bf": "OneMax"}))

    out, notes = [], []
    for title, d, fnames in families:
        R = rows(os.path.join(d, "quality_summary.csv"))
        tests = [r for r in R if r["config"] != "evox"]
        padj = min(holm([float(r["mwu_p"]) for r in tests]))
        width = {g: max(max(abs(float(r["rel_ci_lo"])), abs(float(r["rel_ci_hi"])))
                        for r in tests if r["metric"] == "best" and int(r["gen"]) == g) for g in GENS}
        notes.append((title, len(tests), padj, width))
        out.append(f"\\addlinespace[3pt]\n\\multicolumn{{8}}{{@{{}}l}}{{\\emph{{{title}}}}} \\\\")
        for op in ("de-gen", "ga-gen", "ux-bf"):
            if op not in fnames:
                continue
            large = d.startswith(os.path.join(a.large, ""))
            for cfg in ORDER:
                label = CFG[cfg]
                if large and cfg == "s1":
                    label = CFG["s1w"]
                elif large and cfg == "heur":
                    label = f"scalar, $s={HEUR_S[op]}$, $t_x=512$ (heuristic)"
                cells = []
                for g in GENS:
                    m = [r for r in R if r["op"] == op and r["config"] == cfg and r["metric"] == "best"
                         and int(r["gen"]) == g]
                    if not m:
                        break
                    r = m[0]
                    rel, lo, hi, p = (100 * float(r["rel_to_evox"]), 100 * float(r["rel_ci_lo"]),
                                      100 * float(r["rel_ci_hi"]), float(r["mwu_p"]))
                    ps = f"{p:.2f}" if p >= 0.01 else f"{p:.3f}"
                    if p < 0.05:
                        ps = f"\\textbf{{{ps}}}"
                    cells += [f"${rel:+.1f}$ [${lo:+.1f}$, ${hi:+.1f}$]", ps]
                if len(cells) == 2 * len(GENS):
                    out.append(f"\\texttt{{{ {'de-gen': 'de', 'ga-gen': 'sbx-pm'}.get(op, op) }}} & {label} & " + " & ".join(cells) + " \\\\")
    with open(a.out, "w") as f:
        f.write("% generated by scripts/quality_table.py\n" + "\n".join(out) + "\n")
    print("wrote", a.out)
    for title, n, padj, width in notes:
        print(f"{title}: {n} tests, smallest Holm-adjusted p = {padj:.2f}; widest best-fitness interval "
              + ", ".join(f"gen {g}: +-{100 * w:.1f}%" for g, w in width.items()))


if __name__ == "__main__":
    main()
